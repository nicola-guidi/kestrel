CARD = """<div class=card data-k="{k}">
<a class=shot href="{url}" target=_blank rel=noopener><img loading=lazy src="{src}" alt=""></a>
<div class=body>{badge}<div class=host><a href="{url}" target=_blank rel=noopener>{host}</a></div>
{title}</div></div>"""


def main(argv):
    if len(argv) < 3:
        print(__doc__, file=sys.stderr)
        return 2
    base, program = argv[1], argv[2]
    jsonl = os.path.join(base, "httpx.jsonl")
    shots = from_jsonl(jsonl, base) if os.path.isfile(jsonl) else []
    if not shots:
        shots = from_glob(base)
    if not shots:
        print("SHOTS=0")
        return 0

    cards = []
    for s in shots:
        src = os.path.relpath(s["png"], base)
        url = s["url"] or ""
        host = url.split("://", 1)[-1] if "://" in url else url
        st = s["status"]
        badge = (f'<span class="badge {status_class(st)}">{html.escape(str(st))}</span>'
                 if st not in (None, "") else "")
        title = f'<div class=t title="{html.escape(s["title"])}">{html.escape(s["title"])}</div>' if s["title"] else ""
        k = html.escape((host + " " + s["title"]).lower(), quote=True)
        cards.append(CARD.format(k=k, url=html.escape(url, quote=True), src=html.escape(src, quote=True),
                                 host=html.escape(host), badge=badge, title=title))

    out = os.path.join(base, "index.html")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write(PAGE.format(program=html.escape(program), count=len(shots), cards="\n".join(cards)))
    print(f"SHOTS={len(shots)}")
    print(f"INDEX={out}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
