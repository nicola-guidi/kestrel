#!/usr/bin/env python3
"""Build a screenshot gallery (index.html) for kestrel snapshot.

    gallery.py <snapshots_dir> <program>

Primary source is <dir>/httpx.jsonl (one JSON object per line from `httpx -ss -json`): each
record gives the url, status, title and the saved screenshot path. If that is missing or has no
screenshot paths, it falls back to globbing every *.png under <dir>. Writes <dir>/index.html and
prints SHOTS=<n> / INDEX=<path>.

httpx's exact JSON field names vary between versions, so the screenshot path is found defensively:
known keys first, then any string value that points at a .png on disk.
"""
import glob
import html
import json
import os
import sys

PNG_KEYS = ("screenshot_path_rel", "screenshot_path", "screenshot", "stored_response_path")


def find_png(rec, base):
    """Return a screenshot file path (absolute) for an httpx record, or None."""
    cand = []
    for k in PNG_KEYS:
        v = rec.get(k)
        if isinstance(v, str) and v:
            cand.append(v)
    # last resort: any string value that looks like a png path
    for v in rec.values():
        if isinstance(v, str) and v.lower().endswith(".png"):
            cand.append(v)
    for c in cand:
        p = c if os.path.isabs(c) else os.path.join(base, c)
        if os.path.isfile(p):
            return p
        # some versions store only a basename under <base>/screenshot/
        alt = os.path.join(base, "screenshot", os.path.basename(c))
        if os.path.isfile(alt):
            return alt
    return None


def status_class(code):
    try:
        code = int(code)
    except (TypeError, ValueError):
        return "u"
    return {2: "ok", 3: "redir", 4: "warn", 5: "err"}.get(code // 100, "u")


def from_jsonl(path, base):
    shots = []
    seen = set()
    for line in open(path, encoding="utf-8", errors="replace"):
        line = line.strip()
        if not line:
            continue
        try:
            rec = json.loads(line)
        except ValueError:
            continue
        png = find_png(rec, base)
        if not png or png in seen:
            continue
        seen.add(png)
        shots.append({
            "png": png,
            "url": rec.get("url") or rec.get("input") or "",
            "status": rec.get("status_code") or rec.get("status-code"),
            "title": rec.get("title") or "",
        })
    return shots


def from_glob(base):
    shots = []
    for png in sorted(glob.glob(os.path.join(base, "**", "*.png"), recursive=True)):
        name = os.path.splitext(os.path.basename(png))[0]
        shots.append({"png": png, "url": name.replace("_", "://", 1) if "_" in name else name,
                      "status": None, "title": ""})
    return shots


